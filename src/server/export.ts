/**
 * Exportação de tabelas: CSV (UTF-8 com BOM, separador ";" — abre direto no
 * Excel em pt-BR) e XLSX real (SpreadsheetML mínimo, sem dependências).
 */
import { deflateRawSync } from "node:zlib";

export type ExportCell = string | number | null;

function csvEscape(v: ExportCell): string {
  if (v === null || v === undefined) return "";
  const s = typeof v === "number" ? String(v).replace(".", ",") : String(v);
  // Evita injeção de fórmula ao abrir no Excel.
  const safe = /^[=+\-@\t\r]/.test(s) && typeof v !== "number" ? `'${s}` : s;
  return /[;"\n\r]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
}

export function toCsv(headers: string[], rows: ExportCell[][]): string {
  const lines = [headers.map(csvEscape).join(";"), ...rows.map((r) => r.map(csvEscape).join(";"))];
  return `﻿${lines.join("\r\n")}\r\n`;
}

